"""Build rerun_results.md from the saved outputs in results/seed_*/ (no numbers typed by hand)."""

import json
import statistics as st
import sys
import pandas as pd
from config import PROJECT_ROOT, DATA_DIR

PRIMARY_SEED = 42
RESULTS_ROOT = PROJECT_ROOT / "results"
LEVELS = ["clean", "case", "token", "concat", "string", "whitespace", "encoding", "mixed"]
LEVEL_NAMES = {
    "clean": "Clean (unobfuscated)", "case": "Case randomisation", "token": "Token (backtick + variable renaming)",
    "concat": "String concatenation", "string": "String reordering (format operator)",
    "whitespace": "Whitespace / comment injection", "encoding": "Base64 encoding", "mixed": "Embedded (mixed_malicious)",
}
MODELS = ["TF-IDF + SVM", "CodeBERT"]


def load_seed(seed):
    d = RESULTS_ROOT / f"seed_{seed}"
    r = {"seed": seed}
    for key, name in [("data", "dataset_stats.json"), ("svm", "svm_metrics.json"),
                      ("cb", "codebert_metrics.json"), ("obf", "obfuscation_summary.json")]:
        with open(d / name) as f:
            r[key] = json.load(f)
    r["det"] = {(x["model"], x["level"]): x for x in r["obf"]["malicious_detection"]}
    r["fp"] = {(x["model"], x["level"]): x for x in r["obf"]["benign_false_positive"]}
    return r


def pct(x, nd=1):
    return f"{x * 100:.{nd}f}%"


def rate_cell(row, key):
    return f"{pct(row[key])} ({row['n_flagged_malicious']}/{row['n_scripts']})"


def altered_fraction(seed, cls, level):
    """Share of scripts the technique actually changed (text comparison only)."""
    d = DATA_DIR / "obfuscation" / f"seed_{seed}"
    clean = pd.read_csv(d / f"clean_{cls}.csv")["script_text"].fillna("").values
    prefix = "obfuscated" if cls == "malicious" else "benign_obfuscated"
    obf = pd.read_csv(d / f"{prefix}_{level}.csv")["script_text"].fillna("").values
    return (obf != clean).mean()


def spread(values, fmt):
    if len(values) == 1:
        return fmt(values[0])
    if len(values) == 2:  # an SD from two points is meaningless; show the range instead
        return f"{fmt(st.mean(values))} (range {fmt(min(values))}–{fmt(max(values))})"
    sd = st.stdev(values)
    return f"{fmt(st.mean(values))} ± {fmt(sd)} (min {fmt(min(values))}, max {fmt(max(values))})"


def main():
    seeds = sorted(int(p.name.split("_")[1]) for p in RESULTS_ROOT.glob("seed_*")
                   if (p / "obfuscation_summary.json").exists())
    if PRIMARY_SEED not in seeds:
        sys.exit("primary seed results missing")
    runs = {s: load_seed(s) for s in seeds}
    R = runs[PRIMARY_SEED]
    data, svm, cb, obf = R["data"], R["svm"], R["cb"], R["obf"]
    L = []
    w = L.append

    w("# EE rerun results (fixed methodology)\n")
    w(f"Generated by `make_rerun_summary.py` from `results/seed_*/`. Headline numbers are from **seed {PRIMARY_SEED}** "
      f"(the original config seed); seeds run: {', '.join(map(str, seeds))}. Malicious is the positive class throughout.\n")
    findings_path = PROJECT_ROOT / "rerun_findings.md"
    if findings_path.exists():
        w(findings_path.read_text(encoding="utf-8"))

    # ---------------- Dataset ----------------
    w("## Dataset (§3.1)\n")
    dup = data["duplicates_dropped"]
    both = data["both_labelled_files_removed"]
    w("| Item | Value |\n|---|---|")
    w(f"| Raw files (benign / malicious) | {data['raw_files_benign']} / {data['raw_files_malicious']} |")
    w(f"| **Unique benign scripts** | **{data['unique_benign']}** |")
    w(f"| **Unique malicious scripts** | **{data['unique_malicious']}** |")
    w(f"| Total unique scripts used | {data['unique_benign'] + data['unique_malicious']} |")
    w(f"| **Exact duplicates dropped** | **{dup['total']}** ({dup['benign']} benign, {dup['malicious']} malicious) |")
    w(f"| **Both-labelled scripts removed** | **{data['both_labelled_unique_scripts_removed']} unique scripts** "
      f"({both['benign']} benign + {both['malicious']} malicious files) |")
    w(f"| Empty files skipped | {data['empty_files_skipped']['benign'] + data['empty_files_skipped']['malicious']} |")
    w(f"| Class ratio (benign : malicious) | {data['unique_benign'] / data['unique_malicious']:.2f} : 1 |\n")
    w("| Split | Total | Benign | Malicious |\n|---|---|---|---|")
    for name in ["train", "val", "test"]:
        sp = data["splits"][name]
        w(f"| {name.capitalize()} | {sp['total']} | {sp['benign']} | {sp['malicious']} |")
    w("\nSplit: stratified 80/10/10 after deduplication; no script text occurs in more than one split (asserted in code). "
      "Split sizes are identical for every seed; only membership changes.\n")

    # ---------------- Token lengths ----------------
    tl = obf["clean_malicious_token_lengths"]
    tb = obf["clean_benign_token_lengths"]
    w("## Token lengths (§2.4)\n")
    w("| Item | Value |\n|---|---|")
    w(f"| **% of clean malicious test scripts exceeding 512 tokens** | **{tl['pct_exceeding_512_tokens']:.1f}%** "
      f"(of {tl['n_scripts']}) |")
    w(f"| **Median token length, clean malicious test scripts** | **{tl['median_tokens']:.0f} tokens** |")
    w(f"| (Extra) % of clean benign test scripts exceeding 512 tokens | {tb['pct_exceeding_512_tokens']:.1f}% (of {tb['n_scripts']}) |")
    w(f"| (Extra) Median token length, clean benign test scripts | {tb['median_tokens']:.0f} tokens |\n")
    w("Token counts use CodeBERT's tokenizer and include the `<s>` and `</s>` special tokens, so \">512\" means the "
      "model truncates the script.\n")

    # ---------------- Setup ----------------
    hw = cb["hardware"]
    w("## Setup (§3.4)\n")
    w("| Item | Value |\n|---|---|")
    w(f"| **GPU** | **{hw.get('gpu_name', 'n/a')}, {hw.get('gpu_vram_gib', 'n/a')} GiB VRAM** |")
    w(f"| **Device used for CodeBERT** | **{hw['device']}** (CUDA {hw.get('cuda_version', 'n/a')}, PyTorch {hw['torch_version']}) |")
    w(f"| **CodeBERT batch size** | **{cb['batch_size']}** (peak VRAM allocated {hw.get('peak_vram_allocated_gib', 'n/a')} GiB) |")
    w(f"| CodeBERT learning rate / epochs / max length | {cb['learning_rate']} / {cb['epochs']} / {cb['max_length']} |")
    w(f"| **CodeBERT class weights** | **benign = {cb['class_weights']['benign']:.4f}, malicious = "
      f"{cb['class_weights']['malicious']:.4f}** (n / (2·n_class), from {cb['train_class_counts']['benign']} benign / "
      f"{cb['train_class_counts']['malicious']} malicious training scripts) |")
    w(f"| **SVM chosen C** | **{svm['best_C']}** (validation macro-F1 by C: "
      + ", ".join(f"C={c}: {f:.4f}" for c, f in svm["val_f1_by_C"].items()) + ") |")
    w(f"| SVM class weighting | `class_weight=\"balanced\"` |")
    w(f"| SVM hardware | CPU ({svm['hardware']['processor']}) |")
    w(f"| TF-IDF vocabulary | {svm['vocabulary_size']} char 1–3-grams |\n")

    # ---------------- Unobfuscated ----------------
    w("## Unobfuscated results (§4.1)\n")
    w(f"Test set: {svm['n_test_scripts']} scripts ({data['splits']['test']['benign']} benign, "
      f"{data['splits']['test']['malicious']} malicious).\n")
    rows = [("F1 macro", "f1_macro"), ("F1 benign", "f1_benign"), ("F1 malicious", "f1_malicious"),
            ("Precision macro", "precision_macro"), ("Precision benign", "precision_benign"),
            ("Precision malicious", "precision_malicious"), ("Recall macro", "recall_macro"),
            ("Recall benign", "recall_benign"), ("Recall malicious", "recall_malicious"),
            ("Accuracy", "accuracy"), ("Balanced accuracy", "balanced_accuracy")]
    w("| Metric | TF-IDF + SVM | CodeBERT |\n|---|---|---|")
    for label, key in rows:
        w(f"| {label} | {svm[key]:.4f} | {cb[key]:.4f} |")
    w("\n**Confusion matrices** (positive = malicious):\n")
    w("| Model | TP | FP | FN | TN |\n|---|---|---|---|---|")
    for name, m in [("TF-IDF + SVM", svm), ("CodeBERT", cb)]:
        c = m["confusion_matrix"]
        w(f"| {name} | {c['TP']} | {c['FP']} | {c['FN']} | {c['TN']} |")
    w("\n(TP = malicious flagged malicious, FP = benign flagged malicious, FN = malicious missed, TN = benign passed.)\n")

    # ---------------- Obfuscation ----------------
    w("## Obfuscation detection (§4.2)\n")
    w("### Main table: detection rate on malicious test scripts\n")
    w("| Technique | TF-IDF + SVM | CodeBERT |\n|---|---|---|")
    for lv in LEVELS:
        w(f"| {LEVEL_NAMES[lv]} | {rate_cell(R['det'][('TF-IDF + SVM', lv)], 'detection_rate')} | "
          f"{rate_cell(R['det'][('CodeBERT', lv)], 'detection_rate')} |")
    w("\n### Benign false-positive control: % of obfuscated BENIGN test scripts flagged malicious\n")
    w("| Technique | TF-IDF + SVM FP rate | CodeBERT FP rate | % of benign scripts actually altered | "
      "(ref.) % of malicious scripts altered |\n|---|---|---|---|---|")
    for lv in LEVELS:
        if lv == "mixed":
            continue
        alt_b = "—" if lv == "clean" else pct(altered_fraction(PRIMARY_SEED, "benign", lv))
        alt_m = "—" if lv == "clean" else pct(altered_fraction(PRIMARY_SEED, "malicious", lv))
        w(f"| {LEVEL_NAMES[lv]} | {rate_cell(R['fp'][('TF-IDF + SVM', lv)], 'false_positive_rate')} | "
          f"{rate_cell(R['fp'][('CodeBERT', lv)], 'false_positive_rate')} | {alt_b} | {alt_m} |")
    w("\nThe embedded level has no benign counterpart (it is malicious by construction). A technique that leaves a "
      "script unchanged (e.g. concat on a script that uses none of the targeted cmdlets) cannot change its "
      "prediction, so the \"% altered\" column bounds how much each technique could move the rate.\n")

    pa = obf["embedded_payload_analysis"]
    w("### Embedded payload: visible vs truncated\n")
    w(f"{pa['n_scripts']} embedded scripts, each built around a **test-set** malicious script. "
      f"Definition: {pa['definition']}.\n")
    w("| Subset | n | CodeBERT detection | (ref.) SVM detection |\n|---|---|---|---|")
    for label, key in [("**Payload-visible**", "payload_visible"), ("**Payload-truncated**", "payload_truncated")]:
        s = pa[key]
        cbr = "n/a" if s["codebert_detection_rate"] is None else pct(s["codebert_detection_rate"])
        svr = "n/a" if s["svm_detection_rate"] is None else pct(s["svm_detection_rate"])
        w(f"| {label} | {s['n_scripts']} | {cbr} | {svr} |")
    w(f"| All embedded | {pa['n_scripts']} | {pct(R['det'][('CodeBERT', 'mixed')]['detection_rate'])} | "
      f"{pct(R['det'][('TF-IDF + SVM', 'mixed')]['detection_rate'])} |")
    w(f"\n- **% of embedded scripts whose payload is truncated: {pa['pct_payload_truncated']:.1f}%**")
    w(f"- Median payload start: token {pa['median_payload_start_token']:.0f}")
    w(f"- For contrast, the old (misleading) statistic, % of embedded scripts longer than 512 tokens: "
      f"{pa['pct_scripts_over_512_tokens_old_statistic']:.1f}%. A long script can still have its payload "
      f"inside the window, which is why the two figures differ.\n")

    # ---------------- Cost ----------------
    w("## Cost (§4.3)\n")
    n = svm["n_test_scripts"]
    svm_ms, cb_ms = svm["inference_per_script_ms"], cb["inference_per_script_ms"]
    w("| Item | TF-IDF + SVM | CodeBERT |\n|---|---|---|")
    w(f"| **Training time (end-to-end)** | **{svm['train_time_seconds']:.2f} s** (TF-IDF fit "
      f"{svm['train_time_breakdown_seconds']['tfidf_fit_transform']:.2f} s + SVM fit "
      f"{svm['train_time_breakdown_seconds']['svm_fit']:.2f} s) | **{cb['train_time_seconds']:.1f} s** "
      f"({cb['train_time_seconds'] / 60:.1f} min; 4 epochs incl. tokenisation) |")
    w(f"| **Classification time, whole test set ({n} scripts, end-to-end)** | **{svm['inference_time_seconds']:.3f} s** "
      f"(TF-IDF transform + predict) | **{cb['inference_time_seconds']:.3f} s** (tokenise + forward pass) |")
    w(f"| **Classification time per script (end-to-end)** | **{svm_ms:.3f} ms** | **{cb_ms:.3f} ms** |")
    w(f"| Predict-only (already-vectorised input) | {svm['inference_breakdown_seconds']['svm_predict_only'] * 1000:.3f} ms total, "
      f"{svm['predict_only_per_script_ms']:.5f} ms/script | — |")
    w(f"| Hardware | CPU | GPU ({hw.get('gpu_name', hw['device'])}) |\n")
    w(f"- **Per-script ratio (end-to-end), CodeBERT / SVM: {cb_ms / svm_ms:.2f}×**")
    w(f"- Training-time ratio, CodeBERT / SVM: {cb['train_time_seconds'] / svm['train_time_seconds']:.1f}×")
    w(f"- For comparison, the old (unfair) predict-only ratio on this run would be "
      f"{cb_ms / svm['predict_only_per_script_ms']:.0f}×. The TF-IDF transform is "
      f"{svm['inference_breakdown_seconds']['tfidf_transform'] / svm['inference_time_seconds'] * 100:.2f}% of the "
      f"SVM's end-to-end classification time.")
    nz = svm["nonzero_ngrams_per_test_script"]
    w(f"- **Median non-zero n-grams per test script: {nz['median']:.0f}** (mean {nz['mean']:.0f}, range "
      f"{nz['min']}–{nz['max']}; vocabulary {svm['vocabulary_size']})")
    w(f"- Extra: SVM C search (TF-IDF fit + 4 SVM fits + validation) took {svm['c_search_time_seconds']:.1f} s; "
      f"probability calibration (only used for the ROC chart) {svm['calibration_time_seconds']:.1f} s. CodeBERT "
      f"wall time including per-epoch validation was {cb['train_wall_time_incl_validation_seconds']:.1f} s. "
      f"Neither is included in the end-to-end training times above.\n")

    # ---------------- Variance ----------------
    if len(seeds) > 1:
        w("## Variance across seeds\n")
        w(f"Seeds {', '.join(map(str, seeds))}. Each seed changes the train/val/test split, SVM and CodeBERT "
          f"initialisation/shuffling, and the obfuscation randomness. "
          + ("Format: mean (range across the two seeds). Only two seeds were run (a third was skipped for time), "
             "so treat this as a rough indication of stability, not a confidence interval.\n" if len(seeds) == 2
             else "Format: mean ± sample SD (min, max).\n"))
        f4 = lambda v: f"{v:.4f}"
        fp1 = lambda v: f"{v * 100:.1f}%"
        w("| Metric | TF-IDF + SVM | CodeBERT |\n|---|---|---|")
        for label, key in [("F1 macro", "f1_macro"), ("F1 malicious", "f1_malicious"), ("F1 benign", "f1_benign"),
                           ("Accuracy", "accuracy"), ("Precision malicious", "precision_malicious"),
                           ("Recall malicious", "recall_malicious")]:
            w(f"| {label} | {spread([runs[s]['svm'][key] for s in seeds], f4)} | "
              f"{spread([runs[s]['cb'][key] for s in seeds], f4)} |")
        for lv in LEVELS:
            w(f"| Detection: {LEVEL_NAMES[lv]} | "
              + " | ".join(spread([runs[s]['det'][(m, lv)]['detection_rate'] for s in seeds], fp1) for m in MODELS) + " |")
        for lv in LEVELS:
            if lv == "mixed":
                continue
            w(f"| Benign FP: {LEVEL_NAMES[lv]} | "
              + " | ".join(spread([runs[s]['fp'][(m, lv)]['false_positive_rate'] for s in seeds], fp1) for m in MODELS) + " |")
        for key, label in [("payload_visible", "Embedded, payload-visible"), ("payload_truncated", "Embedded, payload-truncated")]:
            vals_cb = [runs[s]["obf"]["embedded_payload_analysis"][key]["codebert_detection_rate"] for s in seeds]
            vals_svm = [runs[s]["obf"]["embedded_payload_analysis"][key]["svm_detection_rate"] for s in seeds]
            ns = [runs[s]["obf"]["embedded_payload_analysis"][key]["n_scripts"] for s in seeds]
            if None in vals_cb:
                w(f"| {label} (n per seed: {ns}) | n/a | n/a |")
            else:
                w(f"| {label} (n per seed: {ns}) | {spread(vals_svm, fp1)} | {spread(vals_cb, fp1)} |")
        f2 = lambda v: f"{v:.2f}"
        f3 = lambda v: f"{v:.3f}"
        w(f"| Training time (s) | {spread([runs[s]['svm']['train_time_seconds'] for s in seeds], f2)} | "
          f"{spread([runs[s]['cb']['train_time_seconds'] for s in seeds], f2)} |")
        w(f"| Classification per script (ms) | {spread([runs[s]['svm']['inference_per_script_ms'] for s in seeds], f3)} | "
          f"{spread([runs[s]['cb']['inference_per_script_ms'] for s in seeds], f3)} |")
        ratio = [runs[s]["cb"]["inference_per_script_ms"] / runs[s]["svm"]["inference_per_script_ms"] for s in seeds]
        train_ratio = [runs[s]["cb"]["train_time_seconds"] / runs[s]["svm"]["train_time_seconds"] for s in seeds]
        w(f"| Per-script classification ratio, CodeBERT / SVM | {spread(ratio, lambda v: f'{v:.2f}×')} | |")
        w(f"| Training-time ratio, CodeBERT / SVM | {spread(train_ratio, lambda v: f'{v:.1f}×')} | |")
        w(f"| % clean malicious test scripts > 512 tokens | "
          f"{spread([runs[s]['obf']['clean_malicious_token_lengths']['pct_exceeding_512_tokens'] / 100 for s in seeds], fp1)} | (same for both) |")
        w(f"| Chosen C per seed | {', '.join(str(runs[s]['svm']['best_C']) for s in seeds)} | — |")
        w("")

    out = PROJECT_ROOT / "rerun_results.md"
    notes_path = PROJECT_ROOT / "rerun_notes.md"
    text = "\n".join(L)
    if notes_path.exists():
        text += "\n" + notes_path.read_text(encoding="utf-8")
    out.write_text(text, encoding="utf-8")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
